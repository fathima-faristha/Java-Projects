private void openform(javax.swing.JInternalFrame form) {
    desktoppane.removeAll();
    desktoppane.repaint();
    javax.swing.JScrollPane scroll = new javax.swing.JScrollPane(form.getContentPane());
   scroll.setVerticalScrollBarPolicy(javax.swing.JScrollPane.VERTICAL_SCROLLBAR_ALWAYS);
scroll.setHorizontalScrollBarPolicy(javax.swing.JScrollPane.HORIZONTAL_SCROLLBAR_NEVER);
scroll.getVerticalScrollBar().setUnitIncrement(16);
scroll.setBorder(null);
    form.setContentPane(new javax.swing.JPanel(new java.awt.BorderLayout()));
    form.getContentPane().add(scroll);
    form.setMaximizable(true);
    form.setResizable(true);
    desktoppane.add(form);
    form.setBounds(0, 0, desktoppane.getWidth(), desktoppane.getHeight());
    form.setVisible(true);
    try {
        form.setMaximum(true);
    } catch (Exception e) {
    }
}
private void loadcounts() {
    try {
        Class.forName("com.microsoft.sqlserver.jdbc.SQLServerDriver");
        Connection con = DriverManager.getConnection("jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true", "sa", "123");
        Statement st = con.createStatement();
        ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM patients");
        if (rs.next()) lblpatientcount.setText(String.valueOf(rs.getInt(1)));
        rs = st.executeQuery("SELECT COUNT(*) FROM doctors");
        if (rs.next()) lblappointmentcount.setText(String.valueOf(rs.getInt(1)));
        rs = st.executeQuery("SELECT COUNT(*) FROM inventory");
        if (rs.next()) lblpharmacycount.setText(String.valueOf(rs.getInt(1)));
        rs = st.executeQuery("SELECT COUNT(*) FROM lab_tests");
        if (rs.next()) lbllabcount.setText(String.valueOf(rs.getInt(1)));
        rs = st.executeQuery("SELECT COUNT(*) FROM bills");
        if (rs.next()) lblbillcount.setText(String.valueOf(rs.getInt(1)));
        rs = st.executeQuery("SELECT COUNT(*) FROM staff");
        con.close();
    } catch (Exception e) {
    }
}
    
