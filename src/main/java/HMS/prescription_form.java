    private void loadpatients() {
    try {
        Class.forName("com.microsoft.sqlserver.jdbc.SQLServerDriver");
        Connection con = DriverManager.getConnection("jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true", "sa", "123");
        PreparedStatement pst = con.prepareStatement("SELECT record_id, patient_name, diagnosis FROM EMR");
        ResultSet rs = pst.executeQuery();
        cmbpatientname.removeAllItems();
        while (rs.next()) {
            cmbpatientname.addItem(rs.getString("record_id") + " - " + rs.getString("patient_name") + " - " + rs.getString("diagnosis"));
        }
        con.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error loading: " + e.toString());
    }
} 
