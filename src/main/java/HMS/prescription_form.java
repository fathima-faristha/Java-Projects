    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
   String driver = "com.microsoft.sqlserver.jdbc.SQLServerDriver";
String url = "jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true";
String username = "sa";
String password = "123";
        // validation
    String recordID =  cmbpatientname.getSelectedItem().toString().split(" - ")[0];
    String medicineName = cmbmedicinename.getSelectedItem().toString();
    String dosage = txtdosage.getText();
    String duration = txtduration.getText();

    if 
    (recordID.isEmpty() || dosage.isEmpty() || duration.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill all fields!");
        return;
    }
    
    try {
        Class.forName(driver);
        Connection conn = DriverManager.getConnection(url, username, password);
        String sql = "INSERT INTO prescriptions (record_id, medicine_name, dosage, duration) VALUES (?, ?, ?, ?)";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, recordID);
        pst.setString(2, medicineName);
        pst.setString(3, dosage);
        pst.setString(4, duration);
        pst.executeUpdate();
        JOptionPane.showMessageDialog(null, "Prescription saved successfully!");
        
        
        btnviewActionPerformed(null);
        btnclearActionPerformed(null);
        conn.close();
    
    } catch (HeadlessException | ClassNotFoundException | SQLException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    
    }
