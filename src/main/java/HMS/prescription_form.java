         String driver = "com.microsoft.sqlserver.jdbc.SQLServerDriver";
String url = "jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true";
String username = "sa";
String password = "123";

        try {
        Class.forName(driver);
        Connection conn = DriverManager.getConnection(url, username, password);
        String sql = "SELECT prescription_id, record_id, medicine_name, dosage, duration FROM prescriptions";
        PreparedStatement pst = conn.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        DefaultTableModel model = (DefaultTableModel) tblists.getModel();
        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("prescription_id"),
                rs.getString("record_id"),
                rs.getString("medicine_name"),
                rs.getString("dosage"),
                rs.getString("duration")
            });
        }
        conn.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, e.getMessage());
    }
