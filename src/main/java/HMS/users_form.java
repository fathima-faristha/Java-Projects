    private void btnviewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnviewActionPerformed
        // TODO add your handling code here:
        try {
    Class.forName("com.microsoft.sqlserver.jdbc.SQLServerDriver");
    Connection con = DriverManager.getConnection("jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true", "sa", "123");
    PreparedStatement pst = con.prepareStatement("SELECT user_id, username, email, password, role FROM users");
    ResultSet rs = pst.executeQuery();
    DefaultTableModel model = (DefaultTableModel) tblist.getModel();
    model.setRowCount(0);
    while (rs.next()) {
        model.addRow(new Object[]{rs.getString("user_id"), rs.getString("username"), rs.getString("email"), rs.getString("password"), rs.getString("role")});
    }
    con.close();
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Error: " + e.toString());
}
    }//GEN-LAST:event_btnviewActionPerformed

