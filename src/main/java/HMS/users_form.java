    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        // TODO add your handling code here:
        if (txtusername.getText().isEmpty() || txtemail.getText().isEmpty() || String.valueOf(txtpassword.getPassword()).isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please fill all fields");
    return;
}
try {
    Class.forName("com.microsoft.sqlserver.jdbc.SQLServerDriver");
    Connection con = DriverManager.getConnection("jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true", "sa", "123");
    PreparedStatement pst = con.prepareStatement("INSERT INTO users (username, email, password, role) VALUES (?,?,?,?)");
    pst.setString(1, txtusername.getText());
    pst.setString(2, txtemail.getText());
    pst.setString(3, String.valueOf(txtpassword.getPassword()));
    pst.setString(4, cmbrole.getSelectedItem().toString());
    pst.executeUpdate();
    JOptionPane.showMessageDialog(this, "User saved successfully!");
    con.close();
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Error: " + e.toString());
}
    }//GEN-LAST:event_btnsaveActionPerformed

