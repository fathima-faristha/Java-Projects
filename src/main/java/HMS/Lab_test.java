    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        // TODO add your handling code here:
   String driver = "com.microsoft.sqlserver.jdbc.SQLServerDriver";
String url = "jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true";
String username = "sa";
String password = "123";
    // validation
    String patientID = cmbpatient.getSelectedItem().toString();
    String doctorID =cmbdoctor.getSelectedItem().toString();
    String testName = txttestname.getText();
    String results = txtresults.getText();
    String testDate = txttestdate.getText();
    String cost = txtcost.getText();

    if (patientID.isEmpty() || doctorID.isEmpty() || testName.isEmpty() || testDate.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill all fields!");
        return;
    }

    try {
        Class.forName(driver);
        Connection conn = DriverManager.getConnection(url, username, password);
        String sql = "INSERT INTO lab_tests (patient_id, doctor_id, test_name, results, test_date, cost) VALUES (?, ?, ?, ?, ?, ?)";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, patientID);
        pst.setString(2, doctorID);
        pst.setString(3, testName);
        pst.setString(4, results);
        pst.setString(5, testDate);
        pst.setString(6, cost);
        pst.executeUpdate();
        JOptionPane.showMessageDialog(null, "Lab Test saved successfully!");
        btnviewActionPerformed(null);
        conn.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btnsaveActionPerformed

