    private void btnviewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnviewActionPerformed
        // TODO add your handling code here:
        String driver = "com.microsoft.sqlserver.jdbc.SQLServerDriver";
String url = "jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true";
String username = "sa";
String password = "123";
        try {
        Class.forName(driver);
        Connection conn = DriverManager.getConnection(url, username, password);
        String sql = "SELECT test_id, patient_id, doctor_id, test_name, results FROM lab_tests";
        PreparedStatement pst = conn.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        DefaultTableModel model = (DefaultTableModel) tblists.getModel();
        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("test_id"),
                rs.getString("patient_id"),
                rs.getString("doctor_id"),
                rs.getString("test_name"),
                rs.getString("results")
            });
        }
        conn.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }
    
        private void loadpatients() {
    try {
        Class.forName("com.microsoft.sqlserver.jdbc.SQLServerDriver");
        Connection con = DriverManager.getConnection("jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true", "sa", "123");
        PreparedStatement pst = con.prepareStatement("SELECT patient_id, first_name, last_name FROM patients");
        ResultSet rs = pst.executeQuery();
        cmbpatient.removeAllItems();
        while (rs.next()) {
            cmbpatient.addItem(rs.getString("patient_id") + " - " + rs.getString("first_name") + " " + rs.getString("last_name"));
        }
        con.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error loading patients: " + e.toString());
    }
}

