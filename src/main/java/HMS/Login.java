    private void btnforgotActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnforgotActionPerformed
        // TODO add your handling code here:private void btnForgotPasswordActionPerformed(java.awt.event.ActionEvent evt) {
    // database connection
    String driver = "com.microsoft.sqlserver.jdbc.SQLServerDriver";
    String url = "jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true";
    String dbUsername = "sa";
    String dbPassword = "123";

    // validation
    String user = txtusername.getText();

    if (user.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter your username first!");
        return;
    }

    try {
        Class.forName(driver);
        Connection conn = DriverManager.getConnection(url, dbUsername, dbPassword);
        
        // check if username exists
        String sql = "SELECT username FROM users WHERE username = ?";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, user);
        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            // ask for new password
            String newPass = JOptionPane.showInputDialog(this, "Enter new password:");
            String confirmPass = JOptionPane.showInputDialog(this, "Confirm new password:");

            if (newPass == null || newPass.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Password cannot be empty!");
                return;
            }

            if (!newPass.equals(confirmPass)) {
                JOptionPane.showMessageDialog(this, "Passwords do not match!");
                return;
            }

            // update password in database
            String updateSql = "UPDATE users SET password = ? WHERE username = ?";
            PreparedStatement updatePst = conn.prepareStatement(updateSql);
            updatePst.setString(1, newPass);
            updatePst.setString(2, user);
            updatePst.executeUpdate();
            JOptionPane.showMessageDialog(null, "Password reset successfully!");

        } else {
            JOptionPane.showMessageDialog(this, "Username not found!");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_btnforgotActionPerformed

