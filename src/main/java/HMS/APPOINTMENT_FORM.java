    private void loadpatients() {
    try {
        Class.forName("com.microsoft.sqlserver.jdbc.SQLServerDriver");
        Connection con = DriverManager.getConnection("jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true", "sa", "123");
        PreparedStatement pst = con.prepareStatement("SELECT patient_id, first_name, last_name FROM patients");
        ResultSet rs = pst.executeQuery();
        cmbpatientname.removeAllItems();
        while (rs.next()) {
            cmbpatientname.addItem(rs.getString("patient_id") + " - " + rs.getString("first_name") + " " + rs.getString("last_name"));
        }
        con.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error loading patients: " + e.toString());
    }
}
    
