    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        // TODO add your handling code here:
    DefaultTableModel model = (DefaultTableModel) tblbillitems.getModel();
if (txtpatientid.getText().isEmpty() || cmbpatientname.getSelectedItem().toString().isEmpty() || txtbilldate.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please fill patient ID, name and bill date");
    return;
}
if (model.getRowCount() == 0) {
    JOptionPane.showMessageDialog(this, "Please add at least one bill item");
    return;
}
try {
    Class.forName("com.microsoft.sqlserver.jdbc.SQLServerDriver");
    Connection con = DriverManager.getConnection("jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true", "sa", "123");
    String status = "Pending";
    if (rdopaid.isSelected()) {
        status = "Paid";
    }
    double grandtotal = 0;
    for (int i = 0; i < model.getRowCount(); i++) {
        grandtotal = grandtotal + Double.parseDouble(model.getValueAt(i, 4).toString());
    }
    PreparedStatement pst = con.prepareStatement("INSERT INTO bills (patient_id, patient_name, bill_date, total_amount, grand_total, payment_status) VALUES (?,?,?,?,?,?)", PreparedStatement.RETURN_GENERATED_KEYS);
    pst.setString(1, txtpatientid.getText());
    pst.setString(2, cmbpatientname.getSelectedItem().toString());
    pst.setDate(3, java.sql.Date.valueOf(txtbilldate.getText()));
    pst.setDouble(4, grandtotal);
    pst.setDouble(5, grandtotal);
    pst.setString(6, status);
    pst.executeUpdate();
    ResultSet keys = pst.getGeneratedKeys();
    int billid = 0;
    if (keys.next()) {
        billid = keys.getInt(1);
    }
    for (int i = 0; i < model.getRowCount(); i++) {
        PreparedStatement pstitem = con.prepareStatement("INSERT INTO bill_items (bill_id, item_description, item_type, quantity, unit_price, amount) VALUES (?,?,?,?,?,?)");
        pstitem.setInt(1, billid);
        pstitem.setString(2, model.getValueAt(i, 1).toString());
        pstitem.setString(3, "Service");
        pstitem.setInt(4, Integer.parseInt(model.getValueAt(i, 2).toString()));
        pstitem.setDouble(5, Double.parseDouble(model.getValueAt(i, 3).toString()));
        pstitem.setDouble(6, Double.parseDouble(model.getValueAt(i, 4).toString()));
        pstitem.executeUpdate();
    }
    JOptionPane.showMessageDialog(this, "Bill saved successfully! Bill ID: " + billid);
    model.setRowCount(0);
    lbltotalvalue.setText("0");
    con.close();
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Error: " + e.toString());
}

    }//GEN-LAST:event_btnsaveActionPerformed

