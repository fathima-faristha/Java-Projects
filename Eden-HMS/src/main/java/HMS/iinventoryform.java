    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        // TODO add your handling code here:
        String driver = "com.microsoft.sqlserver.jdbc.SQLServerDriver";
String url = "jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true";
String username = "sa";
String password = "123";

    String itemName = txtitemname.getText();
    String quantity = txtquantity.getText();
    String unitPrice = txtunitprice.getText();
    String expiryDate = txtexpirydate.getText();
    String category = txtcategory.getText();
    String supplier = txtsupplier.getText();

    if (itemName.isEmpty() || quantity.isEmpty() || unitPrice.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill all fields!");
        return;
    }

    try {
        Class.forName(driver);
        Connection conn = DriverManager.getConnection(url, username, password);
        String sql = "INSERT INTO inventory (item_name, quantity, unit_price, expiry_date, category, supplier) VALUES (?, ?, ?, ?, ?, ?)";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, itemName);
        pst.setString(2, quantity);
        pst.setString(3, unitPrice);
        pst.setString(4, expiryDate);
        pst.setString(5, category);
        pst.setString(6, supplier);
        pst.executeUpdate();
        JOptionPane.showMessageDialog(null, "Item saved successfully!");
        btnviewActionPerformed(null);
        btnclearActionPerformed(null);
        conn.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_btnsaveActionPerformed

