    private void btnsearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsearchActionPerformed
        // TODO add your handling code here:
       DefaultTableModel model = (DefaultTableModel) tbEMR.getModel();
    model.setRowCount(0);

    String driver="com.microsoft.sqlserver.jdbc.SQLServerDriver";
    String url="jdbc:sqlserver://localhost\\SQLEXPRESS:1433;databaseName=eden;encrypt=true;TrustServerCertificate=true;";
    String username="sa";
    String password="123";

    String keyword = txtkeyword.getText().trim();
    String searchBy = cmbsearchby.getSelectedItem().toString();

    try{
        Class.forName(driver);
        Connection conn = DriverManager.getConnection(url,username,password);

        String sql;
        PreparedStatement PST;

        if(keyword.isEmpty()){
            sql = "SELECT record_id,patient_id,patient_name,doctor_id,doctor_name,diagnosis,treatment,record_date,follow_up_date FROM EMR";
            PST = conn.prepareStatement(sql);
        } else {
            // Search by selected column
            String column;
            switch(searchBy){
    case "Record ID": 
        column = "CAST(record_id AS VARCHAR)"; 
        break;
    case "Patient ID": 
        column = "CAST(patient_id AS VARCHAR)"; 
        break;
    case "Patient Name": 
        column = "patient_name"; 
        break;
    case "Doctor ID": 
        column = "CAST(doctor_id AS VARCHAR)"; 
        break;
    case "Doctor Name": 
        column = "doctor_name"; 
        break;
    case "Diagnosis": 
        column = "diagnosis"; 
        break;
    default: 
        column = "patient_name"; 
        break;
}
            sql = "SELECT record_id,patient_id,patient_name,doctor_id,doctor_name,diagnosis,treatment,record_date,follow_up_date FROM EMR WHERE " + column + " LIKE ?";
            PST = conn.prepareStatement(sql);
            PST.setString(1, "%" + keyword + "%");
        }

        ResultSet rs = PST.executeQuery();
        int count = 0;
        while(rs.next()){
            model.addRow(new Object[]{
                rs.getString("record_id"), rs.getString("patient_id"),
                rs.getString("patient_name"), rs.getString("doctor_id"),
                rs.getString("doctor_name"), rs.getString("diagnosis"),
                rs.getString("treatment"), rs.getString("record_date"),
                rs.getString("follow_up_date")
            });
            count++;
        }
        rs.close();
        PST.close();
        conn.close();

    }catch(HeadlessException | ClassNotFoundException | SQLException e){
        JOptionPane.showMessageDialog(this,e.getMessage());
    }

    }//GEN-LAST:event_btnsearchActionPerformed

