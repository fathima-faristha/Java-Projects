    private void btnviewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnviewActionPerformed
        // TODO add your handling code here:
         String driver = "com.microsoft.sqlserver.jdbc.SQLServerDriver";
        String url = "jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true";
        String username = "sa";
        String password = "123";
        
        try {
        Class.forName(driver);
        Connection conn = DriverManager.getConnection(url, username, password);
        String sql = "SELECT department_id, department_name, description FROM departments";
        PreparedStatement pst = conn.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        DefaultTableModel model = (DefaultTableModel) tbdepartment.getModel();
        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("department_id"),
                rs.getString("department_name"),
                rs.getString("description")
            });
        }
        conn.close();

    } catch (ClassNotFoundException | SQLException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_btnviewActionPerformed

