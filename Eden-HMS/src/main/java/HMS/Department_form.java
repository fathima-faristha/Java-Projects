    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        // TODO add your handling code here:
        String driver = "com.microsoft.sqlserver.jdbc.SQLServerDriver";
        String url = "jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true";
        String username = "sa";
        String password = "123";

    // validation
    String deptName = txtdeptname.getText();
    String description = txtdescription.getText();

    if (deptName.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter Department Name!");
        return;
    }

    try {
        Class.forName(driver);
        Connection conn = DriverManager.getConnection(url, username, password);
        String sql = "INSERT INTO departments (department_name, description) VALUES (?, ?)";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, deptName);
        pst.setString(2, description);
        pst.executeUpdate();
        JOptionPane.showMessageDialog(null, "Department saved successfully!");
        conn.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btnsaveActionPerformed

