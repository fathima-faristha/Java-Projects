    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        // TODO add your handling code here:
        
        if(cmbstaffname.getSelectedItem().toString().isEmpty() || txtuserid.getText().isEmpty()||txtroletitle.getText().isEmpty()||txtphone.getText().isEmpty()||txtemail.getText().isEmpty()||txthiredate.getText().isEmpty()){
            JOptionPane.showMessageDialog(null,"PLEASE FILL ALL THE FIELDS!!!");
        }
         try {
    Class.forName("com.microsoft.sqlserver.jdbc.SQLServerDriver");
    Connection con = DriverManager.getConnection("jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true", "sa", "123");
    PreparedStatement pst = con.prepareStatement ("INSERT INTO staff (user_id, staff_name, role_title, department, phone, email, hire_date) VALUES (?,?,?,?,?,?,?)");
    pst.setString(1,txtuserid.getText());
    pst.setString(2,cmbstaffname.getSelectedItem().toString());
    pst.setString(3, txtroletitle.getText());
    pst.setString(4, cmbdepartment.getSelectedItem().toString());
    pst.setString(5, txtphone.getText());
    pst.setString(6, txtemail.getText());
    pst.setDate(7, java.sql.Date.valueOf(txthiredate.getText()));
    pst.executeUpdate();
    JOptionPane.showMessageDialog(this, "Staff has been recorded saved successfully!");
    con.close();
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
} 
    }
        private void loaddepartments() {
    try {
        Class.forName("com.microsoft.sqlserver.jdbc.SQLServerDriver");
        Connection con = DriverManager.getConnection("jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true", "sa", "123");
        PreparedStatement pst = con.prepareStatement("SELECT department_name FROM departments");
        ResultSet rs = pst.executeQuery();
        cmbdepartment.removeAllItems();
        while (rs.next()) {
            cmbdepartment.addItem(rs.getString("department_name"));
        }
        con.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error loading departments: " + e.getMessage());
}
     
      
    }//GEN-LAST:event_btnsaveActionPerformed

