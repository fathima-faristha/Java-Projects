     private void loadusers() {
    try {
        Class.forName("com.microsoft.sqlserver.jdbc.SQLServerDriver");
        Connection conn = DriverManager.getConnection("jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true", "sa", "123");
        PreparedStatement pst = conn.prepareStatement("SELECT user_id,username FROM users");
        ResultSet rs = pst.executeQuery();
        cmbstaffname.removeAllItems();
        while (rs.next()) {
            cmbstaffname.addItem(rs.getString("user_id") + " - " + rs.getString("username"));
        }
        conn.close();
    } 
    catch (ClassNotFoundException | SQLException e) {
        JOptionPane.showMessageDialog(this, "Error loading users: " + e.toString());
    }
}

