    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
 String driver = "com.microsoft.sqlserver.jdbc.SQLServerDriver";
String url = "jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true";
String username = "sa";
String password = "123";

// validation
    String patientID = txtpatientid.getText();
    String patientName = cmbpatientname.getSelectedItem().toString();
        if (patientID.isEmpty() || patientName.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill patient details!");
        return;
    }

    DefaultTableModel model = (DefaultTableModel) tbitems.getModel();
    if (model.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, "Please dispense at least one medicine!");
        return;
    }

    try {
        Class.forName(driver);
        Connection conn = DriverManager.getConnection(url, username, password);
        for (int i = 0; i < model.getRowCount(); i++) {
            String sql = "INSERT INTO pharmacy_dispense (patient_id, patient_name, medicine_name, quantity, unit_price, total_cost, dispense_date) VALUES (?,?,?,?,?,?,?)";
           PreparedStatement pst = conn.prepareStatement(sql);
pst.setString(1, patientID);
pst.setString(2, cmbpatientname.getSelectedItem().toString().split(" - ")[1]);
pst.setString(3, model.getValueAt(i, 1).toString());
pst.setString(4, model.getValueAt(i, 2).toString());
pst.setString(5, model.getValueAt(i, 3).toString());
pst.setString(6, model.getValueAt(i, 4).toString());
pst.setString(7, model.getValueAt(i, 5).toString());
            pst.executeUpdate();
        }
        JOptionPane.showMessageDialog(null, "Saved successfully!");
        btnviewActionPerformed(null);
        btnclearActionPerformed(null);
        conn.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, e.getMessage());
    }
    }//GEN-LAST:event_btnsaveActionPerformed

