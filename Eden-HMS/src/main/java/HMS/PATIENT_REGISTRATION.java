    private void btnsearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsearchActionPerformed
        // TODO add your handling code here:
    DefaultTableModel model = (DefaultTableModel) tbpatient.getModel();
    model.setRowCount(0);

    String driver="com.microsoft.sqlserver.jdbc.SQLServerDriver";
    String url="jdbc:sqlserver://localhost\\SQLEXPRESS:1433;databaseName=eden;encrypt=true;TrustServerCertificate=true;";
    String username="sa";
    String password="123";

    String keyword = txtsearch.getText().trim();

    try{
        Class.forName(driver);
        Connection conn = DriverManager.getConnection(url,username,password);

        String sql;
        PreparedStatement PST;

        if(keyword.isEmpty()){
            sql = "SELECT patient_id,first_name,last_name,gender,phone_number,email FROM patients";
            PST = conn.prepareStatement(sql);
        } else {
            sql = "SELECT patient_id,first_name,last_name,gender,phone_number,email FROM patients WHERE first_name LIKE ? OR last_name LIKE ? OR patient_id LIKE ?";
            PST = conn.prepareStatement(sql);
            String like = "%" + keyword + "%";
            PST.setString(1, like);
            PST.setString(2, like);
            PST.setString(3, like);
        }

        ResultSet rs = PST.executeQuery();
        int count = 0;
        while(rs.next()){
            model.addRow(new Object[]{
                rs.getString("patient_id"), rs.getString("first_name"),
                rs.getString("last_name"), rs.getString("gender"),
                rs.getString("phone_number"), rs.getString("email")
            });
            count++;
        }
        lbltotal.setText("Total Patients: " + count);

        rs.close();
        PST.close();
        conn.close();

    }catch(HeadlessException | ClassNotFoundException | SQLException e){
        JOptionPane.showMessageDialog(this,e.getMessage());
    }
    }//GEN-LAST:event_btnsearchActionPerformed

