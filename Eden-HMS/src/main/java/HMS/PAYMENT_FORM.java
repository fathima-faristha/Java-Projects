    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        // TODO add your handling code here:
        String driver = "com.microsoft.sqlserver.jdbc.SQLServerDriver";
String url = "jdbc:sqlserver://localhost:1433;databaseName=eden;trustServerCertificate=true";
String username = "sa";
String password = "123";

    // validation
    String billID = txtbillid.getText();
    String amount = txtamount.getText();
    String paymentDate = txtpaymentdate.getText();
    String paymentMode = cmbpaymentmode.getSelectedItem().toString();

    if (billID.isEmpty() || amount.isEmpty() || paymentDate.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill all fields!");
        return;
    }

    try {
        Class.forName(driver);
        Connection conn = DriverManager.getConnection(url, username, password);
        String sql = "INSERT INTO payments (bill_id, amount, payment_date, payment_mode) VALUES (?, ?, ?, ?)";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, billID);
        pst.setString(2, amount);
        pst.setString(3, paymentDate);
        pst.setString(4, paymentMode);
        pst.executeUpdate();
        JOptionPane.showMessageDialog(null, "Payment saved successfully!");
        btnviewActionPerformed(null);
        btnclearActionPerformed(null);
        conn.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_btnsaveActionPerformed

