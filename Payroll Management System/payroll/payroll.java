    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        // TODO add your handling code here:
        String driver="com.microsoft.sqlserver.jdbc.SQLServerDriver";
                String url="jdbc:sqlserver://localhost\\SQLEXPRESS:1433;databaseName=payroll;encrypt=true;trustServerCertificate=true;";
                String userName="sa";
                String password="123";
                
            try{
                if(txtname.getText().isEmpty() ||
                txtemployeeid.getText().isEmpty() ||
                txtbasicsalary.getText().isEmpty() ||
                txtallowance.getText().isEmpty() ||
                txtdeductions.getText().isEmpty())
{
    JOptionPane.showMessageDialog(this,"PLEASE FILL ALL FIELDS");
    return;
}
                 float basicSalary = Float.parseFloat(txtbasicsalary.getText());
        float allowances = Float.parseFloat(txtallowance.getText());
        float deductions = Float.parseFloat(txtdeductions.getText());

        float netPay = basicSalary + allowances - deductions;
        txtnetpay.setText(String.valueOf(netPay));
        
            Class.forName(driver);
            Connection conn=DriverManager.getConnection(url,userName,password);
                String sql="INSERT INTO payroll(employee_id,employee_name,basic_salary ,allowances,deductions,net_pay) VALUES(?,?,?,?,?,?)";
                PreparedStatement PST = conn.prepareStatement(sql);
                PST.setString(1,txtemployeeid.getText());
                PST.setString(2,txtname.getText());
                PST.setFloat(3,basicSalary);
                PST.setFloat(4,allowances);
                PST.setFloat(5,deductions);
                PST.setFloat(6,netPay);
                
                PST.executeUpdate();
                JOptionPane.showMessageDialog(null,"SAVED SUCCESSFULLY!!");
            }
             catch(NumberFormatException e){
        JOptionPane.showMessageDialog(this,"ENTER VALID NUMBERS");
             }
            
            catch(Exception e){
                JOptionPane.showMessageDialog(this,e.getMessage());
            }                                  
    }//GEN-LAST:event_btnsaveActionPerformed

